  await expect(page.getByRole('columnheader', { name: '硬盘', exact: true })).toHaveCount(0)
  await page.getByRole('group',{name:'地区快速筛选'}).getByRole('button',{name:'SG',exact:false}).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
