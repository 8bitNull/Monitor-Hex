test('connection distinguishes realtime, polling, failure and recovery', async ({ page }) => {
  let stream: any
  let socketCount = 0
  await page.routeWebSocket('**/api/ws', ws => { stream=ws; socketCount++ })
  await page.goto('/')
  await expect(page.locator('.node-card')).toHaveCount(6)
  stream.send(JSON.stringify({nodes:nodes()}))
  await expect(page.getByRole('status')).toContainText('实时连接')
  await page.getByLabel('表格视图').click()
  await page.getByLabel('卡片视图').click()
  expect(socketCount).toBe(1)
  stream.close()
  await expect(page.getByRole('status')).toContainText('轮询更新')
  await page.route('**/api/nodes', r=>r.fulfill({status:503,body:'Unavailable'}))
  await expect(page.getByRole('status')).toContainText('连接中断', {timeout:12000})
  await page.unroute('**/api/nodes')
  await expect(page.getByRole('status')).toContainText('轮询更新', {timeout:12000})
  stream.send(JSON.stringify({nodes:nodes()}))
  await expect(page.getByRole('status')).toContainText('实时连接')
  await expect(page.getByText(/最后更新：/)).toBeVisible()
})

test('100 nodes: stable filtering and history concurrency stays bounded', async ({ page }, testInfo) => {
  const base = nodes()[0]
  const list = Array.from({length:100},(_,i)=>({...base,id:i+1,sort:i,name:`Node ${String(i+1).padStart(3,'0')}`,country:i%2?'JP':'US'}))
  await page.route('**/api/nodes',r=>r.fulfill({json:{nodes:list}}))
  let active=0,max=0
  await page.route('**/api/nodes/*/metrics?*',async r=>{active++;max=Math.max(max,active);await new Promise(resolve=>setTimeout(resolve,30));await r.fulfill({json:metrics()});active--})
  await page.goto('/')
  await expect(page.locator('.node-card')).toHaveCount(100)
  await page.getByLabel('表格视图').click()
  const start=performance.now()
  await page.getByRole('group',{name:'地区快速筛选'}).getByRole('button',{name:'US',exact:false}).click()
  await expect(page.locator('tbody tr')).toHaveCount(50)
  const elapsed=performance.now()-start
  console.log(`100-node filter interaction including automation: ${elapsed.toFixed(1)} ms; history max concurrency is checked below`)
  await testInfo.attach('filter-timing', {body:JSON.stringify({nodes:100,elapsedMs:elapsed,note:'Includes browser automation overhead'}),contentType:'application/json'})
  expect(elapsed).toBeLessThan(1500)
  await page.getByLabel('清除地区筛选').click()
  await page.getByRole('columnheader',{name:/所选线路延迟/}).getByRole('button').click()
  await expect(page.locator('.sort-note')).toContainText('100/100', {timeout:20000})
  expect(max).toBeLessThanOrEqual(2)
  await page.screenshot({path:'tests/artifacts/v12-100-nodes.png'})
})

test('silent stream times out and malformed stream falls back without stale overwrite', async ({ page }) => {
  let stream: any
  await page.routeWebSocket('**/api/ws', ws => { stream=ws })
  await page.clock.install()
  await page.goto('/')
  await expect(page.locator('.node-card')).toHaveCount(6)
  stream.send(JSON.stringify({nodes:nodes()}))
  await expect(page.getByRole('status')).toContainText('实时连接')
  await page.clock.fastForward(16000)
  await expect(page.getByRole('status')).toContainText('轮询更新')
  await page.clock.fastForward(6000)
  stream.send('not json')
  await expect(page.getByRole('status')).toContainText('轮询更新')
  await expect(page.locator('.node-card')).toHaveCount(6)
})
