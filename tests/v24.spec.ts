test('settings dialog traps focus, previews choices, closes with Escape and restores trigger',async({page})=>{
 await page.goto('/');const trigger=page.locator('header').getByRole('button',{name:'外观设置',exact:true})
 await toggleSettings(page);const drawer=page.getByRole('dialog',{name:'外观设置',exact:true});await expect(drawer).toBeVisible()
 await expect(page.getByRole('button',{name:'关闭设置'})).toBeFocused()
 await visualSelect(page,'palette','forest');await visualSelect(page,'graph','bar');await visualSelect(page,'layout','compact')
 await expect(page.locator('.next-theme')).toHaveAttribute('data-graph','bar')
 await page.getByRole('navigation',{name:'设置分类'}).getByRole('button',{name:'线路',exact:true}).click()
 await expect(page.getByLabel('主要探测线路')).toBeInViewport()
 for(let i=0;i<20;i++){await page.keyboard.press('Tab');expect(await drawer.evaluate(e=>e.contains(document.activeElement))).toBeTruthy()}
 await page.keyboard.press('Escape');await expect(drawer).toHaveCount(0);await expect(trigger).toBeFocused()
 expect(await page.evaluate(()=>document.body.style.overflow)).not.toBe('hidden')
 await page.reload();await expect(page.locator('.next-theme')).toHaveAttribute('data-palette','forest')
 await page.setViewportSize({width:320,height:844});await toggleSettings(page)
 expect((await drawer.boundingBox())!.width).toBe(320)
 expect(await drawer.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBeTruthy()
 await page.getByRole('button',{name:'关闭设置'}).click();await expect(drawer).toHaveCount(0)
})
