test('return and browser back preserve scroll, focus and view; next node keeps latency tab',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/')
 const target=page.getByRole('button',{name:'查看 Singapore · 新加坡',exact:true})
 await target.scrollIntoViewIfNeeded();await expect(page.locator('.node-card').nth(4).locator('.latency-columns')).toBeVisible();const y=await page.evaluate(()=>scrollY)
 await target.click();await expect(page.locator('.node-detail')).toBeVisible()
 await page.getByRole('button',{name:'网络延迟',exact:true}).click()
 await page.getByRole('button',{name:'下一个节点',exact:true}).click();await expect(page).toHaveURL(/node\/6#latency$/)
 await page.getByRole('button',{name:'返回总览',exact:true}).click()
 await expect(target).toBeFocused();await expect.poll(()=>page.evaluate(()=>scrollY)).toBeCloseTo(y,0)
 await target.click();await expect(page.locator('.node-detail')).toBeVisible();await page.goBack()
 await expect(target).toBeFocused();await expect.poll(()=>page.evaluate(()=>scrollY)).toBeCloseTo(y,0)
})

